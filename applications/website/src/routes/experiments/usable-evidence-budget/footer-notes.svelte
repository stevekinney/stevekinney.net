  <h2 class="text-xl font-bold text-slate-900 dark:text-white">What to keep in mind</h2>
  <ul class="space-y-4 text-slate-700 dark:text-slate-200">
    <li>
      <strong>This is an accounting model, not a measured performance formula.</strong>
      Tokenization varies, and only the host’s own report for the assembled request is authoritative.
    </li>
    <li>
      <strong>What’s left is not uniformly useful.</strong>
      Research on position sensitivity and on degradation as input grows points the same way. Neither
      establishes a universal threshold. A large remaining budget is permission to add evidence, not a
      guarantee that adding it helps.
    </li>
    <li>
      <strong>The terms are not equally movable.</strong>
      Tool definitions are the most reducible, and turning tool search on is a configuration change. History
      grows on its own, so compacting and subagents are the levers. Instructions move when you trim files
      and memory. Reserved generation follows from what you ask for. The margin is a choice, set through
      the autocompact threshold, and shrinking it buys room at the price of less slack before compaction
      fires.
    </li>
  </ul>
